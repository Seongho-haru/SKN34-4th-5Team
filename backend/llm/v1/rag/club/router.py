# 날짜나 팀 이름이 없으면 일반 규칙 질문으로 보고 일정·순위 카테고리는 뺀다.
_DATE_OR_TEAM = re.compile(
    r"\d{1,2}\s*(월|/|\.|-)\s*\d{1,2}|오늘|어제|내일|모레|이번\s*주|다음\s*주|"
    r"LG|엘지|두산|키움|한화|삼성|롯데|기아|KIA|SSG|NC|엔씨|KT|케이티", re.I
)


def detect_categories(question: str) -> list[str]:
    q = question.upper()
    cats = [cat for cat, words in CATEGORY_KEYWORDS.items() if any(w.upper() in q for w in words)]
    if "RULE" in cats and not _DATE_OR_TEAM.search(question):
        cats = [c for c in cats if c not in ("SCHEDULE", "STANDING")]
    return cats
