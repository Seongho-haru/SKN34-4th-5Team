# ── 후처리: 어느 도메인이 답했든 마지막에 같은 말투로 다듬는다 ──────────────
_SOFT = [
    (r"않습니다", "않아요"), (r"있습니다", "있어요"), (r"없습니다", "없어요"), (r"됩니다", "돼요"), (r"됐습니다", "됐어요"),
    (r"합니다", "해요"), (r"했습니다", "했어요"), (r"드립니다", "드려요"), (r"바랍니다", "바라요"), (r"권합니다", "권해요"),
    (r"습니다", "어요"),
]
# 우리 답변에 나올 일이 없는 문자 체계 (모델이 가끔 끝에 섞는 잡음)
_JUNK = re.compile(r"[Ѐ-ԯ֐-᳿ᴀ-᷿-ﬀ-﷿ﹰ-﻿]")
_TAIL_JUNK = re.compile(r"(?<![A-Za-z0-9/])\.{1,4}\s*[a-z]{1,12}\s*$")


def soften(text: str) -> str:
    """'~입니다' 체를 '~예요' 체로. 입니다는 앞 글자 받침에 따라 이에요/예요."""
    def _ipnida(m):
        prev = m.group(1)
        has = "가" <= prev <= "힣" and (ord(prev) - ord("가")) % 28 != 0
        return prev + ("이에요" if has else "예요")
    text = re.sub(r"([가-힣A-Za-z0-9\)%])입니다", _ipnida, text)
    for a, b in _SOFT:
        text = re.sub(a, b, text)
    return text


def clean(text: str) -> str:
    """잡음 문자·중복 공백·꼬리 부스러기 제거"""
    t = re.sub(r"[ \t]{2,}", " ", _JUNK.sub("", text or "")).strip()
    return _TAIL_JUNK.sub("", t).strip()


def finalize(text: str) -> str:
    """디스패처가 모든 답변에 마지막으로 거는 후처리"""
    return soften(clean(text))
